CREATE TRIGGER reorder_watchlist_updated_at
  BEFORE UPDATE ON public.reorder_watchlist
  FOR EACH ROW EXECUTE FUNCTION system.update_updated_at();

CREATE OR REPLACE FUNCTION public.audit_reorder_watchlist_change()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, pg_temp
AS $$
DECLARE
  affected public.reorder_watchlist;
BEGIN
  affected := CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;

  INSERT INTO public.audit_events (
    actor_id,
    action,
    entity_type,
    entity_id,
    details
  )
  VALUES (
    auth.uid(),
    CASE TG_OP
      WHEN 'INSERT' THEN 'reorder_watch_added'
      WHEN 'UPDATE' THEN 'reorder_watch_updated'
      ELSE 'reorder_watch_removed'
    END,
    'reorder_watchlist',
    affected.id::TEXT,
    JSONB_BUILD_OBJECT(
      'sku', affected.sku,
      'product_name', affected.product_name,
      'reorder_point', affected.reorder_point
    )
  );

  RETURN affected;
END;
$$;

CREATE TRIGGER reorder_watchlist_audit
  AFTER INSERT OR UPDATE OR DELETE ON public.reorder_watchlist
  FOR EACH ROW EXECUTE FUNCTION public.audit_reorder_watchlist_change();

ALTER TABLE public.reorder_watchlist ENABLE ROW LEVEL SECURITY;

CREATE POLICY reorder_watchlist_select ON public.reorder_watchlist
  FOR SELECT TO authenticated
  USING (public.can_read_inventory());

CREATE POLICY reorder_watchlist_admin_insert ON public.reorder_watchlist
  FOR INSERT TO authenticated
  WITH CHECK (
    public.is_inventory_admin()
    AND created_by = (SELECT auth.uid())
    AND updated_by = (SELECT auth.uid())
  );

CREATE POLICY reorder_watchlist_admin_update ON public.reorder_watchlist
  FOR UPDATE TO authenticated
  USING (public.is_inventory_admin())
  WITH CHECK (
    public.is_inventory_admin()
    AND updated_by = (SELECT auth.uid())
  );

CREATE POLICY reorder_watchlist_admin_delete ON public.reorder_watchlist
  FOR DELETE TO authenticated
  USING (public.is_inventory_admin());

REVOKE ALL ON public.reorder_watchlist FROM anon, authenticated;
GRANT SELECT, INSERT, DELETE ON public.reorder_watchlist TO authenticated;
GRANT UPDATE (
  source_id,
  product_name,
  supplier,
  reorder_point,
  active,
  notes,
  updated_by
) ON public.reorder_watchlist TO authenticated;

REVOKE EXECUTE ON FUNCTION public.audit_reorder_watchlist_change()
  FROM PUBLIC, anon, authenticated;
