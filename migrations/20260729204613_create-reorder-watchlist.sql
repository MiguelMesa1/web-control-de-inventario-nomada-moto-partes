CREATE TABLE public.reorder_watchlist (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  source_id INTEGER,
  sku TEXT NOT NULL UNIQUE,
  product_name TEXT NOT NULL,
  supplier TEXT,
  reorder_point NUMERIC(14, 2) NOT NULL DEFAULT 10
    CHECK (reorder_point >= 0 AND reorder_point <= 1000000),
  active BOOLEAN NOT NULL DEFAULT TRUE,
  notes TEXT,
  created_by UUID REFERENCES auth.users(id),
  updated_by UUID REFERENCES auth.users(id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT reorder_watchlist_sku_not_blank CHECK (BTRIM(sku) <> ''),
  CONSTRAINT reorder_watchlist_name_not_blank CHECK (BTRIM(product_name) <> '')
);

CREATE INDEX reorder_watchlist_active_idx
  ON public.reorder_watchlist (active, product_name);
CREATE INDEX reorder_watchlist_reorder_point_idx
  ON public.reorder_watchlist (reorder_point);

